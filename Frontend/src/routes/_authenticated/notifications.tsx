import { createFileRoute } from "@tanstack/react-router";
import { Bell, ExternalLink } from "lucide-react";

import { AppLayout } from "@/components/app-layout";
import { BackendStateCard, EmptyState, ErrorState, TableSkeleton, UnavailableSection } from "@/components/data-states";
import { Badge } from "@/components/ui/badge";
import { Button } from "@/components/ui/button";
import { Card, CardContent, CardDescription, CardHeader, CardTitle } from "@/components/ui/card";
import { useBackendQuery, useBackendStatus } from "@/lib/api/hooks";
import { api } from "@/lib/api/endpoints";
import { formatDateTime } from "@/lib/format";
import type { Citation } from "@/lib/api/types";

export const Route = createFileRoute("/_authenticated/notifications")({
  head: () => ({
    meta: [
      { title: "Notifications — VirusWatch" },
      { name: "description", content: "Surveillance notifications with evidence summaries, citations and delivery status." },
      { property: "og:title", content: "Notifications — VirusWatch" },
      { property: "og:description", content: "Surveillance notifications with evidence summaries, citations and delivery status." },
      { property: "og:type", content: "website" },
      { name: "twitter:card", content: "summary" },
    ],
  }),
  component: NotificationsPage,
});

function NotificationsPage() {
  const { status, baseUrl, recheck } = useBackendStatus();
  const ready = status === "ready";
  const notifications = useBackendQuery(["notifications"], (signal) => api.getNotifications(signal), status);

  return (
    <AppLayout>
      <div className="space-y-5">
        <BackendStateCard status={status} baseUrl={baseUrl} onRetry={recheck} />

        {/* Notification history */}
        <Card>
          <CardHeader>
            <CardTitle className="text-base">Notification history</CardTitle>
            <CardDescription>
              Alerts generated by the backend — with evidence, sources and delivery status.
            </CardDescription>
          </CardHeader>
          <CardContent className="space-y-4">
            {!ready ? (
              <TableSkeleton rows={3} />
            ) : notifications.isPending ? (
              <TableSkeleton rows={3} />
            ) : notifications.isError ? (
              <ErrorState description={notifications.error.message} onRetry={() => notifications.refetch()} />
            ) : notifications.data.length === 0 ? (
              <EmptyState
                title="No notifications yet"
                description="The backend has not generated any notifications."
              />
            ) : (
              notifications.data.map((n) => (
                <div key={n.id} className="rounded-xl border border-border bg-background p-4">
                  <div className="flex flex-wrap items-center gap-2">
                    <Bell className="size-4 text-primary" />
                    {n.type ? <Badge variant="secondary">{n.type}</Badge> : null}
                    {n.disease ? <Badge variant="outline">{n.disease}</Badge> : null}
                    {n.geography ? <Badge variant="outline">{n.geography}</Badge> : null}
                    {n.delivery_status ? (
                      <Badge
                        variant="outline"
                        className={
                          n.delivery_status === "sent"
                            ? "border-positive/30 bg-positive/10 text-positive-foreground"
                            : "border-border bg-muted text-muted-foreground"
                        }
                      >
                        {n.delivery_status}
                      </Badge>
                    ) : null}
                    <span className="ml-auto text-xs text-muted-foreground">
                      Created {formatDateTime(n.created_at)}
                      {n.sent_at ? ` · sent ${formatDateTime(n.sent_at)}` : ""}
                    </span>
                  </div>
                  {n.evidence_summary ? (
                    <p className="mt-2.5 text-sm leading-relaxed text-foreground">{n.evidence_summary}</p>
                  ) : null}
                  {n.citations && n.citations.length > 0 ? (
                    <ul className="mt-2 space-y-1">
                      {n.citations.map((c: Citation, i) => (
                        <li key={i} className="text-xs text-muted-foreground">
                          {c.url ? (
                            <a href={c.url} target="_blank" rel="noreferrer noopener" className="inline-flex items-center gap-1 text-primary underline-offset-4 hover:underline">
                              {c.title}
                              <ExternalLink className="size-3" />
                            </a>
                          ) : (
                            c.title
                          )}
                          {c.organization ? ` — ${c.organization}` : ""}
                          {c.publication_date ? ` (${formatDateTime(c.publication_date)})` : ""}
                        </li>
                      ))}
                    </ul>
                  ) : null}
                </div>
              ))
            )}
          </CardContent>
        </Card>

        {/* Preferences */}
        <Card>
          <CardHeader>
            <CardTitle className="text-base">Notification preferences</CardTitle>
            <CardDescription>
              Digest frequency, selected diseases, regions and alert categories.
            </CardDescription>
          </CardHeader>
          <CardContent>
            {!ready ? (
              <UnavailableSection
                title="Preferences"
                endpoint="/api/notifications/preferences"
                reason="Preferences are stored and applied by the backend, which also controls all email delivery and event-trigger decisions."
              />
            ) : (
              <EmptyState
                title="Preferences unavailable"
                description="The backend has not provided its preferences endpoint yet. Nothing is sent from the browser — all delivery happens server-side."
              />
            )}
          </CardContent>
        </Card>
      </div>
    </AppLayout>
  );
}
